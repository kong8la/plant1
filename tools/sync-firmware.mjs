/* 把 downloads/firmware.json 内联成 flash/meta.js，并核对其 SHA-256 与大小。
 * 由 publish.ps1 和 Pages 工作流在打包前调用；页面打开时直接读它，不需要用户选文件。 */
import fs from 'node:fs';
import crypto from 'node:crypto';
import path from 'node:path';

const dir = path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'));
const root = path.join(dir, '..');
const metaPath = path.join(root, 'downloads', 'firmware.json');
const meta = JSON.parse(fs.readFileSync(metaPath, 'utf8'));

const pkgPath = path.join(root, 'downloads', meta.file);
if (!fs.existsSync(pkgPath)) throw new Error('missing package: ' + pkgPath);
const buf = fs.readFileSync(pkgPath);
const sha = crypto.createHash('sha256').update(buf).digest('hex');
if (buf.length !== meta.bytes) throw new Error(`size mismatch: ${buf.length} != ${meta.bytes}`);
if (sha !== meta.sha256) throw new Error(`sha256 mismatch: ${sha} != ${meta.sha256}`);

const inline = {
  name: meta.name, version: meta.version, product: meta.product, file: meta.file,
  bytes: buf.length, sha256: sha, notes: meta.notes || '', source: meta.source || '', build: meta.build || ''
};
const out = '/* generated by tools/sync-firmware.mjs — do not edit */\n' +
  'window.PLANT1_FW = ' + JSON.stringify(inline, null, 2) + ';\n';
fs.writeFileSync(path.join(root, 'flash', 'meta.js'), out);
console.log('flash/meta.js:', inline.name, inline.version, inline.product, buf.length + ' B');
